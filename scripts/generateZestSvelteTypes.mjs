// Generates src/zest.d.ts: Svelte typings for every Zest element.
// Reads the Custom Elements Manifest that ships with @tasteee/zest.
// Run: node scripts/generateZestSvelteTypes.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const manifestPath = 'node_modules/@tasteee/zest/custom-elements.json'
const outputPath = 'src/zest.d.ts'
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))

const allDeclarations = manifest.modules.flatMap((moduleItem) => moduleItem.declarations ?? [])
const elementDeclarations = allDeclarations.filter((declaration) => declaration.tagName)

const getPropertyType = (typeText) => {
	if (!typeText) return 'unknown'
	if (typeText === 'array') return 'any[]'
	if (typeText === 'object') return 'any'
	return typeText.replace(/\s+/g, ' ')
}

const buildPropertyLines = (declaration) => {
	const fields = (declaration.members ?? []).filter((member) => member.kind === 'field')
	return fields.map((field) => `\t\t${field.name}?: ${getPropertyType(field.type?.text)}`)
}

const buildEventLines = (declaration) => {
	const events = declaration.events ?? []
	return events.map((event) => `\t\ton${event.name}?: (event: CustomEvent<any>) => void`)
}

const buildElementBlock = (declaration) => {
	const propertyLines = buildPropertyLines(declaration)
	const eventLines = buildEventLines(declaration)
	const bodyLines = [...propertyLines, ...eventLines].join('\n')
	return `\t'${declaration.tagName}': ZestElementPropsT<{\n${bodyLines}\n\t}>`
}

const elementBlocks = elementDeclarations.map(buildElementBlock).join('\n')

const fileText = `// Generated by scripts/generateZestSvelteTypes.mjs. Do not edit.
import type { HTMLAttributes } from 'svelte/elements'

type ZestElementPropsT<OwnT> = Omit<HTMLAttributes<HTMLElement>, keyof OwnT> & OwnT & { [key: \`data-\${string}\`]: any }

declare module 'svelte/elements' {
	interface SvelteHTMLElements {
${elementBlocks}
	}
}

export {}
`

writeFileSync(outputPath, fileText)
console.log(`Wrote ${elementDeclarations.length} elements to ${outputPath}`)
